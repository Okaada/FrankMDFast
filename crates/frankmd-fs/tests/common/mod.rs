/// File-spec keys of `input.tree` / `input.outside` in source order.
#[derive(Debug, Clone, Default)]
pub struct SpecOrder {
    /// Keys of `input.tree`.
    pub tree: Vec<String>,
    /// Keys of `input.outside`.
    pub outside: Vec<String>,
}

/// Case name → raw key order of its `input.tree` / `input.outside`
/// (serde_json's default `Map` is sorted, the generators used spec order).
pub fn spec_orders(fixture: &str) -> HashMap<String, SpecOrder> {
    use serde::de::{self, Deserializer, IgnoredAny, MapAccess, Visitor};
    use std::fmt;

    struct Keys(Vec<String>);
    impl<'de> serde::Deserialize<'de> for Keys {
        fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
            struct V;
            impl<'de> Visitor<'de> for V {
                type Value = Keys;
                fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                    f.write_str("any")
                }
                fn visit_map<A: MapAccess<'de>>(self, mut m: A) -> Result<Keys, A::Error> {
                    let mut out = Vec::new();
                    while let Some(k) = m.next_key::<String>()? {
                        m.next_value::<IgnoredAny>()?;
                        out.push(k);
                    }
                    Ok(Keys(out))
                }
                fn visit_unit<E: de::Error>(self) -> Result<Keys, E> {
                    Ok(Keys(vec![]))
                }
                fn visit_none<E: de::Error>(self) -> Result<Keys, E> {
                    Ok(Keys(vec![]))
                }
            }
            d.deserialize_any(V)
        }
    }

    struct Input(SpecOrder);
    impl<'de> serde::Deserialize<'de> for Input {
        fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
            struct V;
            impl<'de> Visitor<'de> for V {
                type Value = Input;
                fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                    f.write_str("any")
                }
                fn visit_map<A: MapAccess<'de>>(self, mut m: A) -> Result<Input, A::Error> {
                    let mut o = SpecOrder::default();
                    while let Some(k) = m.next_key::<String>()? {
                        match k.as_str() {
                            "tree" => o.tree = m.next_value::<Keys>()?.0,
                            "outside" => o.outside = m.next_value::<Keys>()?.0,
                            _ => {
                                m.next_value::<IgnoredAny>()?;
                            }
                        }
                    }
                    Ok(Input(o))
                }
                fn visit_seq<A: de::SeqAccess<'de>>(self, mut s: A) -> Result<Input, A::Error> {
                    while s.next_element::<IgnoredAny>()?.is_some() {}
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_str<E: de::Error>(self, _: &str) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_unit<E: de::Error>(self) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_bool<E: de::Error>(self, _: bool) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_i64<E: de::Error>(self, _: i64) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_u64<E: de::Error>(self, _: u64) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
                fn visit_f64<E: de::Error>(self, _: f64) -> Result<Input, E> {
                    Ok(Input(SpecOrder::default()))
                }
            }
            d.deserialize_any(V)
        }
    }

    #[derive(serde::Deserialize)]
    struct RawCase {
        name: String,
        #[serde(default)]
        input: Option<Input>,
    }
    #[derive(serde::Deserialize)]
    struct RawFile {
        cases: Vec<RawCase>,
    }

    let text = fs::read_to_string(frankmd_testkit::golden_path(&format!("{fixture}.json"))).unwrap();
    let raw: RawFile = serde_json::from_str(&text).unwrap();
    raw.cases
        .into_iter()
        .map(|c| (c.name, c.input.map(|i| i.0).unwrap_or_default()))
        .collect()
}

