/// `<TMP>/notes` + `<TMP>/outside` + an app state dir outside both.
pub struct Sandbox {
    tmp: tempfile::TempDir,
    /// `<TMP>` (realpath).
    pub tmp_path: PathBuf,
    /// `<ROOT>` (realpath).
    pub root: PathBuf,
    /// `<OUTSIDE>`.
    pub outside: PathBuf,
    /// App-owned state dir (lock fallback etc.), outside the vault.
    pub state: PathBuf,
}

impl Sandbox {
    /// Empty sandbox.
    pub fn empty() -> Self {
        let tmp = tempfile::tempdir().unwrap();
        let tmp_path = tmp.path().canonicalize().unwrap();
        let root = tmp_path.join("notes");
        let outside = tmp_path.join("outside");
        let state = tmp_path.join("state");
        fs::create_dir_all(&root).unwrap();
        fs::create_dir_all(&outside).unwrap();
        fs::create_dir_all(&state).unwrap();
        Self { tmp, tmp_path, root, outside, state }
    }

    /// Build from `input.tree` / `input.outside` (outside first, as Ruby does),
    /// using `order` for mtime pinning (falls back to sorted key order).
    pub fn from_specs(tree: &Value, outside: &Value, order: Option<&SpecOrder>) -> Self {
        let sb = Self::empty();
        let o = order.cloned().unwrap_or_default();
        sb.build(&sb.outside, outside, &o.outside);
        sb.build(&sb.root, tree, &o.tree);
        sb
    }

    /// Build only a root tree.
    pub fn from_tree(tree: &Value) -> Self {
        Self::from_specs(tree, &Value::Null, None)
    }

    fn subst(&self, s: &str) -> String {
        s.replace("<ROOT>", &self.root.display().to_string())
            .replace("<OUTSIDE>", &self.outside.display().to_string())
    }

    fn build(&self, base: &Path, spec: &Value, order: &[String]) {
        let Some(map) = spec.as_object() else { return };
        let mut keys: Vec<&String> = order.iter().filter(|k| map.contains_key(*k)).collect();
        for k in map.keys() {
            if !keys.contains(&k) {
                keys.push(k);
            }
        }
        let mut i: i64 = 0;
        for rel in keys {
            let val = &map[rel];
            let path = base.join(rel.trim_end_matches('/'));
            if rel.ends_with('/') {
                fs::create_dir_all(&path).unwrap();
                continue;
            }
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).unwrap();
            }
            if let Some(target) = val.get("symlink").and_then(Value::as_str) {
                std::os::unix::fs::symlink(self.subst(target), &path).unwrap();
                continue;
            }
            let bytes: Vec<u8> = if let Some(b64) = val.get("base64").and_then(Value::as_str) {
                base64_decode(b64)
            } else {
                let content = match val {
                    Value::String(s) => s.clone(),
                    Value::Object(o) => o.get("content").and_then(Value::as_str).unwrap_or("").to_owned(),
                    Value::Null => String::new(),
                    other => other.to_string(),
                };
                expand_fed(&content).into_bytes()
            };
            fs::write(&path, bytes).unwrap();
            if let Some(mode) = val.get("mode").and_then(Value::as_u64) {
                use std::os::unix::fs::PermissionsExt;
                fs::set_permissions(&path, fs::Permissions::from_mode(mode as u32)).unwrap();
            }
            let mtime = val.get("mtime").and_then(Value::as_i64).unwrap_or(BASE_MTIME - i * 100);
            set_mtime(&path, mtime);
            i += 1;
        }
    }

    /// Open the vault on `<ROOT>`.
    pub fn vault(&self) -> Vault {
        Vault::open(&self.root, &self.state).unwrap()
    }

    /// Absolute path under the root.
    pub fn abs(&self, rel: &str) -> PathBuf {
        self.root.join(rel)
    }

    /// Write a file under the root (test setup).
    pub fn write(&self, rel: &str, content: &str) {
        let p = self.abs(rel);
        if let Some(parent) = p.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        fs::write(p, content).unwrap();
    }

    /// Create a folder under the root (test setup).
    pub fn mkdir(&self, rel: &str) {
        fs::create_dir_all(self.abs(rel)).unwrap();
    }

    /// Read a file under the root.
    pub fn read(&self, rel: &str) -> String {
        fs::read_to_string(self.abs(rel)).unwrap()
    }

    /// `true` if anything (incl. a dangling symlink) is at `rel`.
    pub fn exists(&self, rel: &str) -> bool {
        fs::symlink_metadata(self.abs(rel)).is_ok()
    }

    /// `mode & 0o7777` of `rel` as octal text (`"600"`).
    pub fn stat_mode(&self, rel: &str) -> String {
        use std::os::unix::fs::PermissionsExt;
        format!("{:o}", fs::symlink_metadata(self.abs(rel)).unwrap().permissions().mode() & 0o7777)
    }

    /// `chmod` under the root.
    pub fn chmod(&self, rel: &str, mode: u32) {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(self.abs(rel), fs::Permissions::from_mode(mode)).unwrap();
    }

    /// Snapshot of the root like `NotesFS.snap`: `{rel: content}`, dirs as
    /// `"x/": null`, symlinks as `{symlink: <normalized target>}`, and a `.fed`
    /// that starts with the template shortened to `<FED_TEMPLATE>…`.
    pub fn snapshot(&self) -> BTreeMap<String, Value> {
        let mut out = BTreeMap::new();
        self.walk(&self.root, &mut out);
        let tpl = fed_template();
        if let Some(Value::String(s)) = out.get(".fed")
            && let Some(rest) = s.strip_prefix(&tpl)
        {
            let v = Value::String(format!("<FED_TEMPLATE>{rest}"));
            out.insert(".fed".into(), v);
        }
        out
    }

    fn walk(&self, dir: &Path, out: &mut BTreeMap<String, Value>) {
        let Ok(rd) = fs::read_dir(dir) else { return };
        let mut entries: Vec<_> = rd.map(|e| e.unwrap()).collect();
        entries.sort_by_key(fs::DirEntry::file_name);
        for e in entries {
            let p = e.path();
            let rel = p.strip_prefix(&self.root).unwrap().to_string_lossy().into_owned();
            let ft = e.file_type().unwrap();
            if ft.is_symlink() {
                let target = fs::read_link(&p).unwrap();
                out.insert(rel, json!({"symlink": self.norm(&target.to_string_lossy())}));
            } else if ft.is_dir() {
                out.insert(format!("{rel}/"), Value::Null);
                self.walk(&p, out);
            } else {
                let bytes = fs::read(&p).unwrap_or_default();
                out.insert(rel, Value::String(String::from_utf8_lossy(&bytes).into_owned()));
            }
        }
    }

    /// `NotesFS.norm` on a string: `<ROOT>`, `<OUTSIDE>`, `<TMP>`, `.<HEX>.tmp`.
    pub fn norm(&self, s: &str) -> String {
        let s = s
            .replace(&self.root.display().to_string(), "<ROOT>")
            .replace(&self.outside.display().to_string(), "<OUTSIDE>")
            .replace(&self.tmp_path.display().to_string(), "<TMP>");
        let re = regex::Regex::new(r"\.[0-9a-f]{12}\.tmp\b").unwrap();
        re.replace_all(&s, ".<HEX>.tmp").into_owned()
    }

    /// [`Sandbox::norm`] over every string (and key) of a JSON value.
    pub fn norm_value(&self, v: &Value) -> Value {
        match v {
            Value::String(s) => Value::String(self.norm(s)),
            Value::Array(a) => Value::Array(a.iter().map(|x| self.norm_value(x)).collect()),
            Value::Object(o) => Value::Object(o.iter().map(|(k, x)| (self.norm(k), self.norm_value(x))).collect()),
            other => other.clone(),
        }
    }

    /// Keep the temp dir alive explicitly (it is removed on drop).
    pub fn tmp(&self) -> &Path {
        self.tmp.path()
    }
}

/// Expand a leading `<FED_TEMPLATE>` placeholder.
pub fn expand_fed(content: &str) -> String {
    match content.strip_prefix("<FED_TEMPLATE>") {
        Some(rest) => format!("{}{rest}", fed_template()),
        None => content.to_owned(),
    }
}

/// Set both atime and mtime (`File.utime`).
pub fn set_mtime(path: &Path, secs: i64) {
    let d = std::time::Duration::from_secs(secs.unsigned_abs());
    let t = if secs >= 0 { std::time::UNIX_EPOCH + d } else { std::time::UNIX_EPOCH - d };
    let f = fs::OpenOptions::new().write(true).open(path).unwrap();
    f.set_times(fs::FileTimes::new().set_accessed(t).set_modified(t)).unwrap();
}

/// Minimal standard base64 decoder (fixtures use `pack("m0")`).
pub fn base64_decode(s: &str) -> Vec<u8> {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = Vec::new();
    let mut buf = 0u32;
    let mut bits = 0;
    for c in s.bytes().filter(|c| *c != b'=' && !c.is_ascii_whitespace()) {
        let v = T.iter().position(|t| *t == c).unwrap() as u32;
        buf = (buf << 6) | v;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buf >> bits) as u8);
            buf &= (1 << bits) - 1;
        }
    }
    out
}

/// Remove the keys a Rails HTTP request creates through `Config` as a side
/// effect (`.fed`, `.frankmd-config.lock`): config creation belongs to
/// `frankmd-config`, not to this crate.
pub fn without_config_side_effects(mut tree: BTreeMap<String, Value>) -> BTreeMap<String, Value> {
    tree.remove(".fed");
    tree.remove(".frankmd-config.lock");
    tree
}

/// Expected `tree_after` (a JSON object) as a sorted map.
pub fn expected_tree(v: &Value) -> BTreeMap<String, Value> {
    v.as_object().map(|o| o.iter().map(|(k, v)| (k.clone(), v.clone())).collect()).unwrap_or_default()
}

/// Fixture error shape `{error: <Rails class>, message}`.
pub fn fs_error_json(e: &FsError) -> Value {
    json!({"error": e.compat_class(), "message": e.to_string()})
}

/// Serialize tree nodes like `NotesFS.json(svc.list_tree)`.
pub fn tree_json(nodes: &[frankmd_core::tree::TreeNode]) -> Value {
    serde_json::to_value(nodes).unwrap()
}

/// `NotesFS.mask_mtimes`: integer mtimes newer than `BASE_MTIME + 10_000_000`
/// (i.e. files written during the case) become `"<TIME>"`.
pub fn mask_mtimes(v: &Value) -> Value {
    match v {
        Value::Array(a) => Value::Array(a.iter().map(mask_mtimes).collect()),
        Value::Object(o) => Value::Object(
            o.iter()
                .map(|(k, x)| {
                    if k == "mtime" && x.as_i64().is_some_and(|m| m > BASE_MTIME + 10_000_000) {
                        (k.clone(), Value::String("<TIME>".into()))
                    } else {
                        (k.clone(), mask_mtimes(x))
                    }
                })
                .collect(),
        ),
        other => other.clone(),
    }
}

/// Compare two JSON values, returning a readable diff message.
pub fn check_eq(what: &str, actual: &Value, expected: &Value) -> Result<(), String> {
    if actual == expected {
        Ok(())
    } else {
        Err(format!("{what}:\n    expected: {expected}\n    actual:   {actual}"))
    }
}

