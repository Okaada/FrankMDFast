//! Shared helpers for frankmd-fs ports and golden conformance tests.
//!
//! Mirrors `tools/golden/ruby/notes_fs_common.rb`: a sandbox `<TMP>/notes`
//! (= `<ROOT>`, realpath) next to `<TMP>/outside` (= `<OUTSIDE>`), tree specs
//! with `<ROOT>`/`<OUTSIDE>` placeholders in symlink targets, `<FED_TEMPLATE>`
//! expansion, `{content, mtime, mode, base64}` values and mtime pinning
//! (`1700000000 - 100*i` in **spec order** of files, which is why the raw key
//! order of each fixture's trees is recovered with [`spec_orders`]).
#![allow(dead_code, unreachable_pub, clippy::disallowed_methods, clippy::unwrap_used, clippy::missing_panics_doc)]

pub mod http;

use frankmd_fs::{FsError, RecentStore, Vault};
use frankmd_testkit::serde_json::{self, Value, json};
use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

/// Default pinned mtime (`NotesFS::BASE_MTIME`).
pub const BASE_MTIME: i64 = 1_700_000_000;

/// `NotesFS::PINNED_NOW` = 2026-01-30T12:34:56.789012Z.
pub fn pinned_now() -> jiff::Timestamp {
    "2026-01-30T12:34:56.789012Z".parse().unwrap()
}

/// The verbatim `.fed` template generated by Rails `Config.new`.
pub fn fed_template() -> String {
    String::from_utf8(frankmd_testkit::golden_bytes("fed_template.fed")).unwrap()
}

/// SHA-256 hex (Rails `Digest::SHA256.hexdigest`).
pub fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect()
}

/// English translation of an i18n key (for model error full messages).
pub fn en(key: &str) -> String {
    let cat = frankmd_i18n::Catalog::load(frankmd_i18n::Locale::En).unwrap();
    cat.t(key, &[])
}

