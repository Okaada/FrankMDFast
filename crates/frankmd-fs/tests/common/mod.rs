/// A stand-in for `frankmd_config::ConfigStore`'s [`RecentStore`] impl: keeps
/// the `recent_files = <json>` line of `<ROOT>/.fed` like Rails `Config#save`
/// (replace an existing or commented `# recent_files =` line in place, else
/// append; create `.fed` from the template when missing; touch the
/// `.frankmd-config.lock`). Only the recents JSON written by the service is
/// under test; the line surgery itself is `frankmd-config`'s contract.
pub struct FedRecentStore {
    /// `<ROOT>/.fed`.
    pub fed: PathBuf,
    /// `<ROOT>/.frankmd-config.lock`.
    pub lock: PathBuf,
}

impl FedRecentStore {
    /// Store for a sandbox root.
    pub fn new(root: &Path) -> Self {
        Self { fed: root.join(".fed"), lock: root.join(".frankmd-config.lock") }
    }

    fn line_re() -> regex::Regex {
        regex::Regex::new(r"(?m)^#?\s*recent_files\s*=\s*(.*)$").unwrap()
    }

    /// The parsed `recent_files` value in `.fed` (for assertions).
    pub fn stored(&self) -> Option<Value> {
        self.load().and_then(|s| serde_json::from_str(&s).ok())
    }
}

impl RecentStore for FedRecentStore {
    fn load(&self) -> Option<String> {
        let text = fs::read_to_string(&self.fed).ok()?;
        let re = regex::Regex::new(r"(?m)^recent_files\s*=\s*(.*)$").unwrap();
        re.captures(&text).map(|c| c[1].trim().to_owned())
    }

    fn modify(&self, f: &mut dyn FnMut(Option<String>) -> Result<String, FsError>) -> Result<bool, FsError> {
        fs::OpenOptions::new().create(true).append(true).open(&self.lock)?;
        let text = fs::read_to_string(&self.fed).unwrap_or_else(|_| fed_template());
        let new_json = f(self.load())?;
        let line = format!("recent_files = {new_json}");
        let re = Self::line_re();
        let out = if re.is_match(&text) {
            re.replace(&text, regex::NoExpand(&line)).into_owned()
        } else {
            let mut t = text.clone();
            if !t.is_empty() && !t.ends_with('\n') {
                t.push('\n');
            }
            t.push_str(&line);
            t.push('\n');
            t
        };
        fs::write(&self.fed, out)?;
        Ok(true)
    }

    fn is_present(&self) -> bool {
        fs::metadata(&self.fed).is_ok_and(|m| m.is_file())
    }
}
